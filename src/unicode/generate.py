#!/usr/bin/env python3
"""
Writes unicode's tables from Go's: src/unicode/tables.cpp, with the data,
and the declarations between the markers in include/gopp/unicode.hpp.

Every table is constant-initialized: plain arrays, RangeTables and
table_maps over them, so they're ready before any static initializer runs.

Run from the repository root with the root of a Go installation of the
version the tables follow (see VERSION below):

    python3 src/unicode/generate.py ~/go/pkg/mod/golang.org/toolchain@v0.0.1-go1.27.3.linux-amd64
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(ROOT, "include", "gopp", "unicode.hpp")
TABLES = os.path.join(ROOT, "src", "unicode", "tables.cpp")
BEGIN = "// BEGIN generated by src/unicode/generate.py\n"
END = "// END generated by src/unicode/generate.py\n"

GO_VERSION = "go1.27.3"


def parse(src):
    """ The declarations of tables.go that go++ needs. """
    out = {
        "range_tables": {},   # _Lu, foldLl, ... -> (r16, r32, latin_offset)
        "exported": [],       # (name, table, comment) in order
        "maps": {},           # Categories, ... -> [(key, value)]
        "case_ranges": [],
        "properties": [],
        "ascii_fold": [],
        "case_orbit": [],
    }
    out["version"] = re.search(r'^const Version = "([^"]+)"', src, re.M).group(1)

    for m in re.finditer(r"^var (\w+) = &RangeTable\{\n(.*?)^\}\n", src, re.M | re.S):
        name, body = m.group(1), m.group(2)
        r16, r32, latin = [], [], 0
        for part in re.finditer(r"(R16|R32): \[\]Range(?:16|32)\{\n(.*?)\n\t\},", body, re.S):
            ranges = [tuple(int(x, 0) for x in t) for t in re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+), (\d+)\}", part.group(2))]
            (r16 if part.group(1) == "R16" else r32).extend(ranges)
        lo = re.search(r"LatinOffset: (\d+)", body)
        if lo:
            latin = int(lo.group(1))
        out["range_tables"][name] = (r16, r32, latin)

    for m in re.finditer(r"^var \(\n(.*?)^\)\n", src, re.M | re.S):
        for line in m.group(1).split("\n"):
            lm = re.match(r"\t(\w+)\s*= (\w+)(?:\s*// (.*))?$", line)
            if lm:
                out["exported"].append((lm.group(1), lm.group(2), lm.group(3)))

    for m in re.finditer(r"^var (\w+) = map\[string\](\*RangeTable|string)\{\n(.*?)^\}\n", src, re.M | re.S):
        entries = re.findall(r'\t"(\w+)":\s*"?(\w+)"?,', m.group(3))
        out["maps"][m.group(1)] = sorted(entries)

    body = re.search(r"^var _CaseRanges = \[\]CaseRange\{\n(.*?)^\}\n", src, re.M | re.S).group(1)
    for t in re.findall(r"\{(0x[0-9A-F]+), (0x[0-9A-F]+), d\{([^}]*)\}\}", body):
        out["case_ranges"].append((int(t[0], 0), int(t[1], 0), [d.strip() for d in t[2].split(",")]))

    body = re.search(r"^var properties = \[MaxLatin1 \+ 1\]uint8\{\n(.*?)^\}\n", src, re.M | re.S).group(1)
    props = [""] * 256
    for i, v in re.findall(r"\t(0x[0-9A-F]{2}): ([^,]+),", body):
        props[int(i, 0)] = v.strip()
    out["properties"] = [p or "0" for p in props]

    body = re.search(r"^var asciiFold = \[MaxASCII \+ 1\]uint16\{\n(.*?)^\}\n", src, re.M | re.S).group(1)
    out["ascii_fold"] = [int(x, 0) for x in re.findall(r"0x[0-9A-F]{4}", body)]

    body = re.search(r"^var caseOrbit = \[\]foldPair\{\n(.*?)^\}\n", src, re.M | re.S).group(1)
    out["case_orbit"] = [(int(a, 0), int(b, 0)) for a, b in re.findall(r"\{(0x[0-9A-F]+), (0x[0-9A-F]+)\}", body)]
    return out


def check(t):
    assert len(t["properties"]) == 256 and len(t["ascii_fold"]) == 128
    assert t["case_ranges"] and t["case_orbit"]
    for name, table, _ in t["exported"]:
        assert table in t["range_tables"], name
    for mname in ("Categories", "Scripts", "Properties", "FoldCategory", "FoldScript"):
        for key, table in t["maps"][mname]:
            assert table in t["range_tables"] or table in {n for n, _, _ in t["exported"]}, (mname, key)


def cpp_name(go_name):
    """ The C++ name of an unexported table: _Lu -> Lu_, foldLl -> foldLl. """
    return go_name[1:] + "_" if go_name.startswith("_") else go_name


def table_target(name, exported):
    """ The data behind a map's value: an exported name refers to its table. """
    return cpp_name(exported.get(name, name))


def write_tables(t):
    exported = {n: tab for n, tab, _ in t["exported"]}
    w = []
    w.append(f"// Code generated by src/unicode/generate.py from {GO_VERSION}'s unicode/tables.go. DO NOT EDIT.\n")
    w.append("// clang-format off\n")
    w.append("#include <gopp/unicode.hpp>\n\n#include \"tables.hpp\"\n\n")
    w.append("namespace gopp::unicode {\n\nnamespace {\n\n")
    for name, (r16, r32, latin) in t["range_tables"].items():
        c = cpp_name(name)
        if r16:
            w.append(f"constexpr Range16 {c}r16[] = {{\n")
            w.extend(f"    {{0x{a:04x}, 0x{b:04x}, {s}}},\n" for a, b, s in r16)
            w.append("};\n")
        if r32:
            w.append(f"constexpr Range32 {c}r32[] = {{\n")
            w.extend(f"    {{0x{a:x}, 0x{b:x}, {s}}},\n" for a, b, s in r32)
            w.append("};\n")
        w.append(f"constexpr RangeTable {c}{{{c + 'r16' if r16 else '{}'}, {c + 'r32' if r32 else '{}'}, {latin}}};\n\n")

    for mname, entries in t["maps"].items():
        if mname == "CategoryAliases":
            w.append(f"constexpr table_map<std::string_view>::entry {mname}_[] = {{\n")
            w.extend(f'    {{"{k}", "{v}"}},\n' for k, v in entries)
        else:
            w.append(f"constexpr table_map<const RangeTable*>::entry {mname}_[] = {{\n")
            w.extend(f'    {{"{k}", &{table_target(v, exported)}}},\n' for k, v in entries)
        w.append("};\n\n")

    w.append("constexpr CaseRange CaseRanges_[] = {\n")
    for lo, hi, d in t["case_ranges"]:
        w.append(f"    {{0x{lo:04X}, 0x{hi:04X}, {{{', '.join(d)}}}}},\n")
    w.append("};\n\n")
    w.append("}  // namespace\n\n")

    w.append(f'const std::string_view Version = "{t["version"]}";\n\n')
    for name, table, _ in t["exported"]:
        w.append(f"constinit const RangeTable* const {name} = &{cpp_name(table)};\n")
    w.append("\n")
    for mname in t["maps"]:
        kind = "std::string_view" if mname == "CategoryAliases" else "const RangeTable*"
        w.append(f"constinit const table_map<{kind}> {mname}{{{mname}_}};\n")
    w.append("constinit const std::span<const CaseRange> CaseRanges{CaseRanges_};\n\n")
    # From graphic.go.
    for name, tables in (("GraphicRanges", "L M N P S Zs"), ("PrintRanges", "L M N P S")):
        refs = ", ".join(f"&{table_target(n, exported)}" for n in tables.split())
        w.append(f"namespace {{\nconstexpr const RangeTable* const {name}_[] = {{{refs}}};\n}}\n")
        w.append(f"constinit const std::span<const RangeTable* const> {name}{{{name}_}};\n")
    w.append("\n")

    w.append("namespace detail {\n\n")
    w.append("constinit const uint8 properties[MaxLatin1 + 1] = {\n")
    for i, p in enumerate(t["properties"]):
        w.append(f"    {p},  // 0x{i:02X}\n")
    w.append("};\n\n")
    w.append("constinit const uint16 asciiFold[MaxASCII + 1] = {\n")
    for i in range(0, 128, 8):
        w.append("    " + " ".join(f"0x{x:04X}," for x in t["ascii_fold"][i:i + 8]) + "\n")
    w.append("};\n\n")
    w.append("constexpr foldPair caseOrbit_[] = {\n")
    w.extend(f"    {{0x{a:04X}, 0x{b:04X}}},\n" for a, b in t["case_orbit"])
    w.append("};\n")
    w.append("constinit const std::span<const foldPair> caseOrbit{caseOrbit_};\n\n")
    w.append("}  // namespace detail\n\n")
    w.append("}  // namespace gopp::unicode\n")
    with open(TABLES, "w") as f:
        f.write("".join(w))


def write_header(t):
    d = []
    d.append(f"// unicode.Version: the Unicode edition of the tables.\n")
    d.append("extern const std::string_view Version;\n\n")
    d.append("// The categories, scripts and properties: unicode::Lu, unicode::Latin,\n")
    d.append("// unicode::White_Space, ...\n")
    for name, _, comment in t["exported"]:
        line = f"extern const RangeTable* const {name};"
        d.append(f"{line}{'  // ' + comment if comment else ''}\n")
    d.append("\n")
    d.append("// unicode.Categories, unicode.Scripts and unicode.Properties: the tables\n")
    d.append("// above by name (\"Lu\", \"Greek\", \"White_Space\").\n")
    d.append("extern const table_map<const RangeTable*> Categories;\n")
    d.append("extern const table_map<const RangeTable*> Scripts;\n")
    d.append("extern const table_map<const RangeTable*> Properties;\n")
    d.append("// unicode.CategoryAliases: the categories' long names (\"Letter\" is \"L\").\n")
    d.append("extern const table_map<std::string_view> CategoryAliases;\n")
    d.append("// unicode.FoldCategory and unicode.FoldScript: the code points outside\n")
    d.append("// a category or script that fold (SimpleFold) into it.\n")
    d.append("extern const table_map<const RangeTable*> FoldCategory;\n")
    d.append("extern const table_map<const RangeTable*> FoldScript;\n")
    d.append("// unicode.CaseRanges: the case mappings of all letters that have them.\n")
    d.append("extern const std::span<const CaseRange> CaseRanges;\n")
    src = open(HEADER).read()
    i, j = src.index(BEGIN) + len(BEGIN), src.index(END)
    with open(HEADER, "w") as f:
        f.write(src[:i] + "".join(d) + src[j:])


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    goroot = sys.argv[1]
    version = open(os.path.join(goroot, "VERSION")).readline().strip()
    if version != GO_VERSION:
        sys.exit(f"{goroot} is {version}, not {GO_VERSION}")
    t = parse(open(os.path.join(goroot, "src", "unicode", "tables.go")).read())
    check(t)
    write_tables(t)
    write_header(t)


if __name__ == "__main__":
    main()
