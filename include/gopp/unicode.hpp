inline constexpr rune MaxRune = 0x10FFFF;          // the largest valid code point
inline constexpr rune ReplacementChar = 0xFFFD;    // stands for invalid code points
inline constexpr rune MaxASCII = 0x7F;             // the largest ASCII value
inline constexpr rune MaxLatin1 = 0xFF;            // the largest Latin-1 value

// unicode.Range16: the code points Lo to Hi inclusive, every Stride.
struct Range16 {
    uint16 Lo;
    uint16 Hi;
    uint16 Stride;
};

// unicode.Range32: as Range16, for code points that don't fit in 16 bits.
// Lo and Hi are at least 1<<16.
struct Range32 {
    uint32 Lo;
    uint32 Hi;
    uint32 Stride;
};

// unicode.RangeTable: a set of code points as sorted, non-overlapping
// ranges: the 16-bit ones in R16, the rest in R32.
struct RangeTable {
    std::span<const Range16> R16;
    std::span<const Range32> R32;
    int LatinOffset = 0;  // the number of entries in R16 with Hi <= MaxLatin1
};

// The indexes into CaseRange::Delta.
inline constexpr int UpperCase = 0;
inline constexpr int LowerCase = 1;
inline constexpr int TitleCase = 2;
inline constexpr int MaxCase = 3;

// A CaseRange Delta of UpperLower means that the range alternates upper
// and lower case letters, starting with upper.
inline constexpr rune UpperLower = MaxRune + 1;

// unicode.CaseRange: simple case conversion for the code points Lo to Hi:
// add Delta[c] for case c (zero if a code point is in that case already).
struct CaseRange {
    uint32 Lo;
    uint32 Hi;
    rune Delta[MaxCase];
};

// unicode.SpecialCase: language-specific case mappings that take priority
// over the standard ones, such as TurkishCase.
struct SpecialCase {
    std::span<const CaseRange> ranges;

    rune ToUpper(rune r) const noexcept;
    rune ToTitle(rune r) const noexcept;
    rune ToLower(rune r) const noexcept;
};

// The sorted, constant maps of the package (Go's map[string]V), such as
// Scripts. m[name] gives V{} (nullptr, "") for a name it doesn't have, as
// a Go map gives the zero value. Iterating gives the entries in name order:
//
//     for (auto [name, table] : unicode::Scripts) { ... }
template <typename V>
class tableMap {
public:
    struct entry {
        std::string_view key;
        V value;
    };

    constexpr tableMap(std::span<const entry> entries) noexcept : entries_(entries) {}

    constexpr V operator[](std::string_view key) const noexcept {
        auto it = find(key);
        return it == entries_.end() ? V{} : it->value;
    }
    constexpr bool contains(std::string_view key) const noexcept { return find(key) != entries_.end(); }
    constexpr std::size_t size() const noexcept { return entries_.size(); }
    constexpr std::size_t len() const noexcept { return entries_.size(); }
    constexpr auto begin() const noexcept { return entries_.begin(); }
    constexpr auto end() const noexcept { return entries_.end(); }

private:
    constexpr auto find(std::string_view key) const noexcept {
        auto it = std::lower_bound(entries_.begin(), entries_.end(), key,
                                   [](const entry& e, std::string_view k) { return e.key < k; });
        return it != entries_.end() && it->key == key ? it : entries_.end();
    }

    std::span<const entry> entries_;
};

