//
//     unicode::IsUpper(U'Ä');                 // true
//     unicode::ToLower(U'Ä');                 // U'ä'
//     unicode::Is(unicode::Han, U'世');       // true
//     unicode::In(r, unicode::Letter, unicode::Digit);
//     auto greek = unicode::Scripts["Greek"]; // nullptr for an unknown name
//
